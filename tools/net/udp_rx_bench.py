"""Host side of fpga/udp_probe: how fast can this PC take UDP from the FPGA?

The probe bitstream (SRAM only) answers ARP for 10.0.0.125 and takes one
command datagram on UDP 39153; it then streams `count` packets back to the
sender's address and port, generated by the FPGA at up to line rate, and can
interleave heartbeat packets sent through Gowin's MAC wrapper (the CPU's path).
Counters come once a second on COM7 (fps_probe's frame format).

    python tools/net/udp_rx_bench.py                         # 12800 rows of 1116 B, line rate
    python tools/net/udp_rx_bench.py --count 128000 --hb-us 100
    python tools/net/udp_rx_bench.py --len 8660 --count 1600  # jumbo: 8 rows per packet
    python tools/net/udp_rx_bench.py --sweep-ifg 12 40 80 160 255
    python tools/net/udp_rx_bench.py --uart COM7 --status    # probe counters only
    python tools/net/udp_rx_bench.py --stop

Every received packet is checked after the run (so the receive loop stays
lean): magic, command id, sequence (lost / duplicated / out of order), the
data pattern and the CRC-32 the FPGA computed. Layout: fpga/udp_probe/src/
probe_udp_gen.v; plan: docs/architecture/UDP_FRAME_STREAM_PLAN.md, stage 1.
"""
import argparse
import random
import socket
import struct
import sys
import time
import zlib

HOST, PORT = "10.0.0.125", 39153
APP_HDR = 16                    # 'UPSB', cmd_id, udp_len, seq, count
WIRE_OVERHEAD = 42 + 4 + 20     # Eth+IP+UDP headers, FCS, preamble + 12-byte gap

# UART report words, in the order of rep_word() in fpga/udp_probe/src/udp_probe_top.v
WORDS = ["uptime", "miim_physr", "gen_pkt", "gen_arp_statto", "hb", "txento_underrun_init",
         "mux_a", "mux_b", "mux_statto_abort", "max_hold_a", "rx_frames", "rx_err_arp",
         "rx_cmd_id", "first_garp_flags", "host_ip", "host_port_len"]
NW = len(WORDS)


# ------------------------------------------------------------------ UART
def read_report(port, timeout=3.0):
    """The next whole report: 0x5A 0xA5, NW big-endian words, byte sum."""
    t0 = time.time()
    state = 0
    while time.time() - t0 < timeout:
        b = port.read(1)
        if not b:
            continue
        if state == 0:
            state = 1 if b == b"\x5a" else 0
        elif b == b"\xa5":
            body = port.read(4 * NW + 1)
            if len(body) == 4 * NW + 1 and (sum(body[:-1]) & 0xFF) == body[-1]:
                return dict(zip(WORDS, struct.unpack(f">{NW}I", body[:-1])))
            state = 0
        else:
            state = 1 if b == b"\x5a" else 0
    return None


def fmt_report(r):
    physr = r["miim_physr"] & 0xFFFF
    speed = {0: 10, 1: 100, 2: 1000}.get((physr >> 4) & 3, "?")
    link = "link UP" if physr & 4 else "link DOWN"
    if physr == 0xFFFF:
        link, speed = "PHYSR not read", "?"
    hold_us = r["max_hold_a"] / 125.0
    return (f"t={r['uptime']} s | PHY {link} {speed}M {'FD' if physr & 8 else 'HD'} "
            f"(PHYSR {physr:#06x}, MIIM fails {r['miim_physr'] >> 16}) | wrapper init "
            f"{r['txento_underrun_init'] & 1}, heartbeats {r['hb']}, TX_EN timeouts {r['txento_underrun_init'] >> 16}\n"
            f"  gen: stream {r['gen_pkt']}, ARP replies {r['gen_arp_statto'] >> 16}, gratuitous ARP {(r['first_garp_flags'] >> 8) & 0xFF} (mod 256), "
            f"stat timeouts {r['gen_arp_statto'] & 0xFFFF}, worst first-byte wait "
            f"{r['first_garp_flags'] >> 16} cyc, FIFO underruns {(r['txento_underrun_init'] >> 1) & 0x7FFF} (must be 0), "
            f"streaming {r['first_garp_flags'] & 1}\n"
            f"  mux: wrapper {r['mux_a']}, gen {r['mux_b']}, stat timeouts "
            f"{r['mux_statto_abort'] >> 16}, aborts {r['mux_statto_abort'] & 0xFFFF}, "
            f"wrapper waited at most {r['max_hold_a']} cyc ({hold_us:.1f} us)\n"
            f"  rx: frames {r['rx_frames']}, errors {r['rx_err_arp'] >> 16}, ARP requests "
            f"{r['rx_err_arp'] & 0xFFFF}, commands {r['rx_cmd_id'] >> 16} (last id "
            f"{r['rx_cmd_id'] & 0xFFFF:#06x}) from {socket.inet_ntoa(struct.pack('>I', r['host_ip']))}:"
            f"{r['host_port_len'] >> 16}, udp_len {r['host_port_len'] & 0xFFFF}")


# ------------------------------------------------------------------ stream
def command(cmd_id, udp_len, count, gap=0, ifg=0, hb_us=0):
    flags = 1 if hb_us else 0
    return struct.pack("!4sHHIHBBH", b"UPRC", cmd_id, udp_len, count, gap, ifg, flags, hb_us)


def warm_up(a, limit_s=60.0):
    """Send a one-packet command every second until the probe answers.

    Seconds it took, or None. Right after the FPGA is loaded the office switch
    delivered no unicast to the board's MAC - not the commands, not Windows'
    unicast ARP probes - for ~20 s, until Windows broadcast an ARP request and
    the probe answered it; the probe's own gratuitous ARP did not help (board
    sessions of 13.10.2026, fpga/udp_probe/README.md).
    """
    s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    s.connect((a.host, a.port))
    s.settimeout(1.0)
    t0 = time.time()
    try:
        while time.time() - t0 < limit_s:
            s.send(command(0xFFFF, 20, 1))
            try:
                while True:
                    p = s.recv(64)
                    if len(p) == 20 and p[0:4] == b"UPSB":
                        return time.time() - t0
            except socket.timeout:
                pass
    finally:
        s.close()
    return None


def run(a, udp_len, count, gap, ifg, hb_us, quiet=False):
    """One command, receive, verify. Returns a dict of results."""
    s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    s.setsockopt(socket.SOL_SOCKET, socket.SO_RCVBUF, a.rcvbuf * 1024 * 1024)
    got_buf = s.getsockopt(socket.SOL_SOCKET, socket.SO_RCVBUF)
    s.connect((a.host, a.port))               # only datagrams from the probe get through
    s.settimeout(a.first_timeout)

    slot = max(udp_len, 64)
    n_max = count + count // 4 + 64           # room for heartbeats
    buf = bytearray(slot * n_max)
    mv = memoryview(buf)
    lens = []
    cmd_id = random.randint(1, 0xFFFE)
    s.send(command(cmd_id, udp_len, count, gap, ifg, hb_us))

    # Times are of stream packets only; the run ends with the count, or when no
    # stream packet came for idle_timeout - heartbeats go on after the stream
    # (until the next command) and must not keep the loop alive.
    t_first = t_last = None
    n_stream = 0
    i = 0
    try:
        while n_stream < count and i < n_max:
            try:
                n = s.recv_into(mv[i * slot:(i + 1) * slot], slot)
            except socket.timeout:
                if t_last is None or time.perf_counter() - t_last > a.idle_timeout:
                    break
                continue
            now = time.perf_counter()
            lens.append(n)
            i += 1
            if n == udp_len:
                n_stream += 1
                if t_first is None:
                    t_first = now
                    s.settimeout(0.05)
                t_last = now
            elif t_last is not None and now - t_last > a.idle_timeout:
                break
    finally:
        s.close()

    # ---- verify
    pattern = bytes(range(256)) * (udp_len // 256 + 2)
    seen = set()
    lost = dup = ooo = bad_crc = bad_pat = bad_hdr = 0
    hb = 0
    last_seq = -1
    for k, n in enumerate(lens):
        p = mv[k * slot:k * slot + n]
        if n == 22 and p[0:4] == b"UPHB":          # UDP length 30 = 8 + 22 bytes of payload
            hb += 1
            continue
        if n != udp_len or p[0:4] != b"UPSB":
            bad_hdr += 1
            continue
        cid, plen, seq, cnt = struct.unpack_from("!HHII", p, 4)
        if cid != cmd_id or plen != udp_len or cnt != count:
            bad_hdr += 1
            continue
        if seq in seen:
            dup += 1
            continue
        seen.add(seq)
        if seq < last_seq:
            ooo += 1
        last_seq = max(last_seq, seq)
        if zlib.crc32(p[:-4]) != struct.unpack_from("!I", p, n - 4)[0]:
            bad_crc += 1
        b0 = seq & 0xFF
        if p[APP_HDR:-4] != pattern[b0:b0 + udp_len - APP_HDR - 4]:
            bad_pat += 1
    lost = count - len(seen)
    # Frames of rows (1280 packets each, the frame stream's unit) that came in
    # whole - what "resend the whole frame" (plan § 8) has to live with - and
    # how the losses group: one burst of 1000 costs one frame, 1000 single
    # losses cost all of them.
    rows_per_pkt = max(1, (udp_len - 20) // 1080)    # 1116: one row, 8660: eight (jumbo)
    rows = max(1, 1280 // rows_per_pkt)              # packets per 1080x1280 frame
    n_frames = count // rows
    have = bytearray(count)
    for q in seen:
        if q < count:
            have[q] = 1
    intact = sum(1 for f in range(n_frames) if have[f * rows:(f + 1) * rows].count(0) == 0)
    bursts, longest, run_len = 0, 0, 0
    for q in range(count):
        if not have[q]:
            run_len += 1
        elif run_len:
            bursts += 1; longest = max(longest, run_len); run_len = 0
    if run_len:
        bursts += 1; longest = max(longest, run_len)
    dt = (t_last - t_first) if (t_first and t_last and t_last > t_first) else 0.0
    rate_pps = (len(seen) - 1) / dt if dt else 0.0
    payload_mbps = rate_pps * udp_len * 8 / 1e6
    wire_mbps = rate_pps * (udp_len + WIRE_OVERHEAD) * 8 / 1e6
    r = dict(udp_len=udp_len, count=count, ifg=ifg, gap=gap, got=len(seen), lost=lost, dup=dup,
             ooo=ooo, bad_crc=bad_crc, bad_pat=bad_pat, bad_hdr=bad_hdr, hb=hb, dt_ms=dt * 1e3,
             pps=rate_pps, payload_mbps=payload_mbps, wire_mbps=wire_mbps, rcvbuf=got_buf,
             frames=n_frames, intact=intact, bursts=bursts, longest=longest)
    if not quiet:
        print(f"udp_len {udp_len}, count {count}, IFG {ifg or 12}, gap {gap} | SO_RCVBUF {got_buf // 1024} KB")
        print(f"  received {len(seen)} / {count}: lost {lost}, duplicates {dup}, out of order {ooo}, "
              f"CRC errors {bad_crc}, pattern errors {bad_pat}, foreign/bad header {bad_hdr}, heartbeats {hb}")
        print(f"  first -> last {dt * 1e3:.1f} ms: {rate_pps / 1e3:.1f} kpkt/s, payload {payload_mbps:.0f} Mbit/s, "
              f"on the wire {wire_mbps:.0f} Mbit/s")
        print(f"  losses in {bursts} bursts, longest {longest} packets")
        if n_frames:
            print(f"  as 1080x1280 frames ({rows_per_pkt} row(s) per packet, {rows} packets): "
                  f"{intact} of {n_frames} whole, {dt * 1e3 / (count / rows):.1f} ms per frame")
    return r


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--host", default=HOST)
    ap.add_argument("--port", type=int, default=PORT)
    ap.add_argument("--len", type=int, default=1116, help="UDP payload per packet, 20..8972 (1116 = one row)")
    ap.add_argument("--count", type=int, default=12800, help="packets (12800 = ten frames of rows)")
    ap.add_argument("--gap", type=int, default=0, help="extra idle 8 ns cycles after each packet")
    ap.add_argument("--ifg", type=int, default=0, help="MAC inter-frame gap, bytes 8..255 (0 = 12)")
    ap.add_argument("--hb-us", type=int, default=0, help="heartbeat through the wrapper every N us (0 = off)")
    ap.add_argument("--repeat", type=int, default=1)
    ap.add_argument("--sweep-ifg", type=int, nargs="*", help="run once per IFG value")
    ap.add_argument("--sweep-gap", type=int, nargs="*", help="run once per gap value (8 ns cycles; IFG beyond 255 bytes)")
    ap.add_argument("--rcvbuf", type=int, default=64, help="SO_RCVBUF, MB")
    ap.add_argument("--first-timeout", type=float, default=2.0)
    ap.add_argument("--idle-timeout", type=float, default=0.5)
    ap.add_argument("--uart", help="COM port of the probe's report, e.g. COM7")
    ap.add_argument("--status", action="store_true", help="print the probe's counters and exit")
    ap.add_argument("--stop", action="store_true", help="send count 0 (stop a stream) and exit")
    ap.add_argument("--no-warmup", action="store_true", help="skip waiting until the probe answers")
    a = ap.parse_args()

    port = None
    if a.uart:
        import serial
        port = serial.Serial(a.uart, 115200, timeout=0.5)
        r = read_report(port)
        print(fmt_report(r) if r else f"no report on {a.uart}")
        if a.status:
            return 0 if r else 1

    if a.stop:
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        s.sendto(command(0, 20, 0), (a.host, a.port))
        print("stop sent")
        return 0

    if not a.no_warmup:
        w = warm_up(a)
        print(f"probe answers after {w:.1f} s" if w is not None else "probe does not answer (60 s)")
        if w is None:
            return 1

    ok = True
    sweep = [("IFG", v, a.gap, v if v != 12 else 0) for v in (a.sweep_ifg or [])] + \
            [("gap", v, v, a.ifg) for v in (a.sweep_gap or [])]
    if sweep:
        # kpkt/s and Mbit/s are what the PC took in: received packets over first -> last
        print(f"{'':>4} {'value':>6} {'got':>7} {'lost':>6} {'bursts':>6} {'kpkt/s':>7} {'Mbit/s':>7} "
              f"{'whole frames':>12}  crc/pat/hdr")
        for name, v, gap, ifg in sweep:
            r = run(a, a.len, a.count, gap, ifg, a.hb_us, quiet=True)
            print(f"{name:>4} {v:>6} {r['got']:>7} {r['lost']:>6} {r['bursts']:>6} {r['pps'] / 1e3:>7.1f} "
                  f"{r['wire_mbps']:>7.0f} {r['intact']:>5} of {r['frames']:<4}  "
                  f"{r['bad_crc']}/{r['bad_pat']}/{r['bad_hdr']}")
            ok &= not (r["bad_crc"] or r["bad_pat"] or r["dup"])
            time.sleep(0.3)
    else:
        for _ in range(a.repeat):
            r = run(a, a.len, a.count, a.gap, a.ifg, a.hb_us)
            ok &= not (r["lost"] or r["bad_crc"] or r["bad_pat"] or r["dup"])
            time.sleep(0.3)

    if port:
        time.sleep(1.2)
        r = read_report(port)
        print(fmt_report(r) if r else "no report after the run")
        port.close()
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
