#!/usr/bin/env python3
"""regs.toml -> Rust + Verilog + C Header + Markdown. usage: regmap.py [--check]"""
import hashlib
import pathlib
import sys
import tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
src = (ROOT / "regs.toml").read_bytes()
spec = tomllib.loads(src.decode("utf-8"))
MAP_HASH = int.from_bytes(hashlib.sha256(src).digest()[:4], "little")
BASE_ADDR = spec["device"].get("base_addr", 0xF8000900)


def mask(bits: str):
    hi, lo = (map(int, bits.split(":")) if ":" in bits else (int(bits), int(bits)))
    return ((1 << (hi - lo + 1)) - 1) << lo, lo


rust = [
    "// AUTO-GENERATED BY tools/npu/regmap.py FROM regs.toml -- DO NOT EDIT",
    f"pub const NPU_BASE_ADDR: usize = 0x{BASE_ADDR:08X};",
    f"pub const MAP_HASH: u32 = 0x{MAP_HASH:08X};",
    "#[allow(dead_code)]",
]
ver = [
    "// AUTO-GENERATED BY tools/npu/regmap.py FROM regs.toml -- DO NOT EDIT",
    f"localparam [31:0] NPU_MAP_HASH = 32'h{MAP_HASH:08X};",
]
cheader = [
    "/* AUTO-GENERATED BY tools/npu/regmap.py FROM regs.toml -- DO NOT EDIT */",
    "#ifndef GENERATED_NPU_REGS_H_",
    "#define GENERATED_NPU_REGS_H_",
    "",
    "#include <stdint.h>",
    "",
    f"#define NPU_BASE_ADDR          0x{BASE_ADDR:08X}UL",
    f"#define NPU_MAP_HASH           0x{MAP_HASH:08X}UL",
]
doc = [
    f"# {spec['device']['name']} v{spec['device']['version']} — MAP_HASH 0x{MAP_HASH:08X}",
    "",
    f"- **Шина:** `{spec['device']['bus'].upper()}`",
    f"- **Базовый адрес:** `0x{BASE_ADDR:08X}`",
    f"- **Хеш карты (`MAP_HASH`):** `0x{MAP_HASH:08X}`",
    "",
    "| Смещение | Адрес | Регистр | Доступ | Поля | Описание |",
    "|---|---|---|---|---|---|",
]

for r in spec["register"]:
    n, off = r["name"], r["offset"]
    rust.append(f"pub const {n}: usize = 0x{off:04X};")
    ver.append(f"localparam [7:0] ADDR_{n} = 8'h{off:02X};")
    cheader.append(f"#define NPU_REG_{n}_OFF 0x{off:03X}UL")
    cheader.append(f"#define NPU_REG_{n} (*(volatile uint32_t *)(NPU_BASE_ADDR + 0x{off:03X}UL))")
    fs = []
    for f in r.get("fields", []):
        m, s = mask(f["bits"])
        rust += [
            f"pub const {n}_{f['name']}_MASK: u32 = 0x{m:08X};",
            f"pub const {n}_{f['name']}_SHIFT: u32 = {s};",
        ]
        ver.append(f"localparam [31:0] {n}_{f['name']}_MASK = 32'h{m:08X};")
        ver.append(f"localparam integer {n}_{f['name']}_SHIFT = {s};")
        cheader.append(f"#define NPU_{n}_{f['name']}_MASK  0x{m:08X}UL")
        cheader.append(f"#define NPU_{n}_{f['name']}_SHIFT {s}U")
        fs.append(f"`{f['name']}[{f['bits']}]` ({f['access']})")
    doc.append(
        f"| `0x{off:02X}` | `0x{BASE_ADDR + off:08X}` | `{n}` | `{r['access']}` | {', '.join(fs) or '—'} | {r.get('desc', '')} |"
    )

cheader += ["", "#endif /* GENERATED_NPU_REGS_H_ */"]

files = {
    ROOT / "generated" / "regs.rs": "\n".join(rust) + "\n",
    ROOT / "generated" / "regs.vh": "\n".join(ver) + "\n",
    ROOT / "generated" / "REGMAP.md": "\n".join(doc) + "\n",
    ROOT / "fpga" / "src" / "npu_regs.vh": "\n".join(ver) + "\n",
    ROOT / "firmware" / "src" / "app" / "npu_regs.h": "\n".join(cheader) + "\n",
}

check = "--check" in sys.argv
for p, text in files.items():
    if check:
        if not p.exists() or p.read_text(encoding="utf-8") != text:
            sys.exit(f"OUT OF DATE: {p} — запусти tools/npu/regmap.py")
    else:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")

print(f"MAP_HASH = 0x{MAP_HASH:08X} | {'check OK' if check else 'generated'}")
