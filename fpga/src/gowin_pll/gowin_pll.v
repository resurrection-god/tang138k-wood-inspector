// clkout4 was added to this IP by hand: it clocks the Lane 4 writer.
// It comes from the SAME PLL as DDR3_CLK_IN, so it stays phase-aligned with the
// memory-controller PLL, which is what the Lane 4 clock rule actually requires -
// the rule is about phase alignment, not about being the identical net.
// ENCLK4 is already tied high inside the instantiation below.
//
// DDR3-1066 (17.09.2026, ERRORS 1.5): VCO 1600 MHz gives the memory
// clock 533.333 MHz and Lane 4 exactly a quarter of it. 125 MHz cannot be made
// from 1600, so GTX_CLK and ETH_CLK moved to Gowin_PLL_ETH; clkout1 and clkout3
// are unused here now.
//
// Experiment E3 (29.09.2026): VCO 800 MHz is within the datasheet (DS1239: 650..1300;
// 1600 was outside it, warning PA1019), memory at 400 MHz is within the SoC datasheet
// (MUG1031 table 4-2). LANE4_CLK: E3a - 133.333 MHz = 1/3 of memory (datasheet: >= 1/4),
// E3b - 100 MHz = exactly 1/4. The SoC DDR_CLK is left alone (100 MHz from
// Gowin_PLL_AE350), unlike E2 (ERRORS 1.11) - one variable at a time.
